import type { MusicStyle, ProgressionTemplate } from '../../core/practice/types';

type Entry = [
  id: string,
  name: string,
  mode: 'major' | 'minor',
  difficulty: number,
  chords: string,
  tags?: string,
  weight?: number,
];

function catalog(style: MusicStyle, entries: Entry[]): ProgressionTemplate[] {
  return entries.map(([id, name, mode, difficulty, chords, tags = '', weight = 3]) => ({
    id: `${style}-${id}`,
    name,
    style,
    mode,
    difficulty,
    chords: chords.split(' '),
    weight,
    tags: tags.split(' ').filter(Boolean),
  }));
}

